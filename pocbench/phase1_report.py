"""Render the Phase 1 results (results/phase1/*.json) as docs/phase1-profile.md."""

import csv
import gzip
import json
from collections import Counter
from pathlib import Path

from pocbench import shapes

GIB = 1024 ** 3
# Neon: 4 GB of RAM per CU; the local file cache can use up to 75% of it.
# Used only when the tier probe has not recorded the real limit.
NOMINAL_CACHE_BYTES_PER_CU = 0.75 * 4 * GIB


def _load(path: Path) -> dict | None:
    return json.loads(path.read_text()) if path.exists() else None


def _ms(x) -> str:
    if x is None:
        return "-"
    return f"{x:,.0f}" if x >= 100 else f"{x:.1f}"


def _gb(b: int) -> str:
    return f"{b / GIB:.2f} GiB"


def _cache_bytes(setting: str | None) -> int | None:
    """neon.file_cache_size_limit, e.g. '3072 MB' or '805306368 B'."""
    if not setting:
        return None
    value, _, unit = setting.partition(" ")
    scale = {"": 1, "B": 1, "kB": 1024, "MB": 1024 ** 2, "GB": GIB}.get(unit)
    return int(float(value) * scale) if scale else None


def truth_mapping(results: Path, manifest: dict) -> dict[str, Counter]:
    """Designed shape -> profiler shapes, from the ground-truth file and the log.
    Read here, after profiling, only to check the profiler's work."""
    log_path, truth_path = results / "query-log.jsonl.gz", results / "query-log-truth.csv.gz"
    if not (log_path.exists() and truth_path.exists()):
        return {}
    ids = {v["template"]: sid for sid, v in manifest["shapes"].items()}
    truth = {}
    with gzip.open(truth_path, "rt") as fh:
        for seq, shape in csv.reader(fh):
            truth[int(seq)] = shape
    out: dict[str, Counter] = {}
    with gzip.open(log_path, "rt") as fh:
        for line in fh:
            e = json.loads(line)
            sid = ids.get(shapes.normalize(e["sql"]).template, "?")
            out.setdefault(truth[e["seq"]], Counter())[sid] += 1
    return out


def render(results: Path, run_url: str | None = None) -> str:
    prof = _load(results / "profile.json")
    man = _load(results / "split-manifest.json")
    corp = _load(results / "corpus.json")
    tier = _load(results / "tier-probe.json")
    if prof is None or man is None:
        raise FileNotFoundError(f"{results} needs profile.json and split-manifest.json")
    h, cap = prof["headline"], prof["capture"]
    lines = ["# Phase 1 profile", "",
             f"RC1-629. Generated by `pocbench profile-report` from `{results}/`."]
    if run_url:
        lines.append(f"Run: {run_url}")
    db = prof["dataset"]["database_bytes"]
    lines += ["", "## Headline", "",
              f"Profiled **{h['log_rows_profiled']:,} log rows** (the profiling slice of a "
              f"{h['log_rows_total']:,}-row query log) and found **{h['shapes']} query shapes** "
              f"over a **{_gb(db)}** dataset of {h['dataset_rows']:,} rows. "
              f"{len(h['dominant_shapes'])} shapes "
              f"({', '.join(h['dominant_shapes'])}) account for "
              f"{h['dominant_time_share']:.0%} of capture time.", ""]

    lines += ["## Dataset to cache", "",
              "The ratio is a design parameter, not a claim that results transfer to "
              "other scales (config-space.toml [dataset]).", "",
              "| Tier (CU) | Compute cache | Dataset / cache | Source |",
              "| ---: | ---: | ---: | --- |"]
    for cu in (0.25, 0.5, 1, 2, 4):
        setting = (tier or {}).get("tiers", {}).get(str(cu), {}).get("settings", {})
        measured = _cache_bytes(setting.get("neon.file_cache_size_limit"))
        cache = measured or NOMINAL_CACHE_BYTES_PER_CU * cu
        src = "neon.file_cache_size_limit" if measured else "nominal (75% of 4 GB per CU)"
        lines.append(f"| {cu} | {_gb(cache)} | {db / cache:.1f}x | {src} |")

    v = cap["stats_validity"]
    lines += ["", "## Capture", "",
              f"Closed loop, {prof['capture_config']['sessions']} sessions, "
              f"{prof['capture_config']['measure_seconds']:.0f} s measured after a "
              f"{prof['capture_config']['warmup_seconds']:.0f} s warm-up, on the naive baseline at "
              f"{prof['capture_config']['cu']} CU (ADR 0016). Profiling slice only. "
              f"{cap['observations']:,} observations, {cap['throughput_qps']} queries/s. "
              f"Probe (`SELECT 1`) p50 {_ms(cap['probe']['p50_ms'])} ms, "
              f"p99 {_ms(cap['probe']['p99_ms'])} ms.", "",
              f"Statistics valid: **{'yes' if v['valid'] else 'NO'}** "
              f"({', '.join(f'{k} {ok}' for k, ok in v['checks'].items())}). "
              f"Server up since {v['before']['postmaster_start']}; "
              f"pg_stat_statements reset at {v['before']['pgss_reset']}.", ""]

    lines += ["## Shapes", "",
              "Ordered by total capture time. A timed-out query counts its full timeout. "
              "Percentiles marked * are below the tail floor "
              f"(p95 {prof['tail_floor_observations']['p95']:,} and p99 "
              f"{prof['tail_floor_observations']['p99']:,} observations): reported, not "
              "supported.", "",
              "| Shape | What | Log share | Obs | p50 ms | p95 ms | p99 ms | Err+TO | Time share "
              "| Selectivity | Max q-error | Plan |",
              "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |"]
    for s in prof["shapes"]:
        c, ts = s["capture"], s["tail_supported"]
        sel = s["selectivity"]
        plan = s["plan"]
        notes = ", ".join(x.split(":", 1)[1] for x in plan["scans"]) or "-"
        if plan["spills"]:
            notes += f"; spills {plan['spills']}/{plan['samples']}"
        if plan["timeouts"]:
            notes += f"; EXPLAIN timeouts {plan['timeouts']}/{plan['samples']}"
        fails = (c["error_count"] or 0) + (c["timeout_count"] or 0)
        lines.append(
            f"| {s['shape']} | {s['label']} | {s['log_share']:.1%} | {c['sample_count'] or 0:,} "
            f"| {_ms(c['p50_ms'])} | {_ms(c['p95_ms'])}{'' if ts['p95'] else '*'} "
            f"| {_ms(c['p99_ms'])}{'' if ts['p99'] else '*'} | {fails:,} | {s['time_share']:.1%} "
            f"| {'-' if sel['median'] is None else f'{sel['median']:.2e}'} "
            f"| {sel['max_q_error'] or '-'} | {notes} |")

    mapping = truth_mapping(results, man)
    if mapping:
        clean = sum(1 for c in mapping.values() if len(c) == 1)
        distinct = {next(iter(c)) for c in mapping.values() if len(c) == 1}
        lines += ["", "## Shape recovery check", "",
                  f"Against the generator's ground truth (read only after profiling): "
                  f"{clean} of {len(mapping)} designed shapes map to exactly one profiler shape, "
                  f"onto {len(distinct)} distinct shapes.", "",
                  "| Designed shape | Profiler shape |", "| --- | --- |"]
        for name, c in sorted(mapping.items(), key=lambda kv: min(kv[1])):
            lines.append(f"| {name} | {', '.join(f'{k} ({n:,})' for k, n in c.most_common())} |")

    lines += ["", "## Held-out split", "",
              f"Account-level, stratified by account-size decile, "
              f"{man['rule']['held_out_fraction']:.0%} held out, seed {man['rule']['seed']}, "
              f"best of {man['rule']['candidates']} candidates "
              f"(chose {man['rule']['chosen_candidate']}, "
              f"worst per-shape deviation {man['rule']['worst_shape_deviation']:.1%}). "
              f"Profiling {man['slices']['profiling']['entries']:,} rows over "
              f"{len(man['slices']['profiling']['accounts']):,} accounts; held out "
              f"{man['slices']['held_out']['entries']:,} rows over "
              f"{len(man['slices']['held_out']['accounts']):,} accounts. "
              f"Log sha256 `{man['log']['sha256'][:16]}...`, assignment sha256 "
              f"`{man['assignment_sha256'][:16]}...`.", "",
              "Distinct-instance floor for a supported tail: "
              f"p95 {man['tail_floors']['p95']['distinct_instances']:,}, "
              f"p99 {man['tail_floors']['p99']['distinct_instances']:,}.", "",
              "| Shape | Profiling | Held out | Held-out share | No tenant | Held-out distinct "
              "| Held-out tail supported |", "| --- | ---: | ---: | ---: | ---: | ---: | --- |"]
    for sid, x in man["shapes"].items():
        sup = {q: "yes" if ok else "no" for q, ok in x["held_out_tail_supported"].items()}
        lines.append(f"| {sid} | {x['profiling']:,} | {x['held_out']:,} "
                     f"| {x['held_out_fraction']:.1%} | {x['no_tenant']:,} "
                     f"| {x['held_out_distinct']:,} "
                     f"| p95 {sup['p95']}, p99 {sup['p99']} |")

    lines += ["", "## Measured sizes", "",
              "| Table | Rows | Heap | Heap bytes/row | Indexes (PK) |",
              "| --- | ---: | ---: | ---: | ---: |"]
    for name, t in prof["dataset"]["tables"].items():
        lines.append(f"| {name} | {t['rows']:,} | {_gb(t['heap_bytes'])} "
                     f"| {t['heap_bytes_per_row']} | {_gb(t['index_bytes'])} |")
    lines += ["", "| Index | Size |", "| --- | ---: |"]
    for name, b in sorted(prof["index_bytes"].items()):
        if name.startswith(("naive_", "cand_")):
            lines.append(f"| {name} | {b / 1024 ** 2:,.0f} MiB |")
    if corp:
        lines += ["", f"Corpus load: {corp['load_seconds'] / 60:.0f} min; "
                  f"{corp['events_generated_ids']:,} event ids generated, "
                  f"{corp['churn_keep_fraction']:.1%} kept after the churn filter (D5)."]

    if tier:
        lines += ["", "## Tier probe", "",
                  "Phase 0 open question: why the funnel scan ran slower at 1 CU than at "
                  f"0.25 CU. Spike dataset, hottest campaign, alone and from "
                  f"{tier['sessions']} concurrent sessions.", "",
                  "| CU | max_connections | worker processes | parallel workers | per gather "
                  "| work_mem | alone ms | workers alone | concurrent median ms | workers launched "
                  "(concurrent) |",
                  "| ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |"]
        for cu, t in tier["tiers"].items():
            st = t["settings"]
            alone = t["alone"][-1]
            launched = Counter(t["concurrent"]["workers_launched"])
            lines.append(
                f"| {cu} | {st.get('max_connections')} | {st.get('max_worker_processes')} "
                f"| {st.get('max_parallel_workers')} | {st.get('max_parallel_workers_per_gather')} "
                f"| {st.get('work_mem')} | {_ms(alone['execution_ms'])} "
                f"| {alone['workers_launched']}/{alone['workers_planned']} "
                f"| {_ms(t['concurrent']['median_ms'])} "
                f"| {', '.join(f'{k}: {n}' for k, n in sorted(launched.items()))} |")
    return "\n".join(lines) + "\n"
